#!/usr/bin/env python3
"""
Extract the coordinates of the three figures from the pilot JSON files.

Every number plotted in paper/figures/*.tex comes from a field written by one of the
pilot scripts; this file is the only place where a JSON field is turned into a figure
coordinate, so a reader can check a plotted point without reading the plots.

  figures/data/fig1-ratchet-prefix.dat   t, S(t)            pilot24_results.json c_design
  figures/data/fig1-ratchet-floor.dat    K, measured, ratchet and terminal predictions
                                                           pilot5c + pilot24
  figures/data/fig2-escape.dat           step, exact, e5m2    pilot23_results.json
  figures/data/fig2-edge.dat             step, upper edge    pilot23_results.json
  figures/data/fig2-delta.dat            safety, delta*(p)   pilot23_results.json
  figures/data/fig3-format.dat           bits, err (E5M2/E4M3/bf16) pilot21_results.json
  figures/data/fig3-ladder.dat           bits, err (mixed)   pilot21_results.json

Writes the .dat files and prints them.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "paper", "figures", "data")
C_CERT = 0.142


def load(name):
    """read a result JSON next to this script, or from ../results in the archive layout."""
    for base in (HERE, os.path.join(os.path.dirname(HERE), "results")):
        p = os.path.join(base, name)
        if os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                return json.load(f)
    raise FileNotFoundError(name)


def w(name, header, rows):
    path = os.path.join(OUT, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write("% " + name + " - generated by data/make_figure_data.py\n")
        f.write(header + "\n")
        for r in rows:
            f.write(" ".join(("%.6g" % v) if isinstance(v, float) else str(v) for v in r) + "\n")
    print("=" * 78)
    print(path)
    with open(path, encoding="utf-8") as f:
        print(f.read(), end="")


def fig1():
    p24 = load("pilot24_results.json")
    p5c = load("pilot5c_results.json")
    d = p24["c_design"]["L0.001_K7"]
    w("fig1-ratchet-prefix.dat", "t S",
      [[t + 1, v] for t, v in enumerate(d["prefix_curve"])])
    rows = []
    for K in (5, 6, 7):
        sh = p5c[f"grid_K{K}"]["shipped"]
        cd = p24["c_design"][f"L0.001_K{K}"]
        u8 = 2.0 ** -8
        rows.append([K, sh["err8"], sh["err11"], cd["S_pert"], sh["S"],
                     C_CERT * u8 * cd["S_pert"], C_CERT * u8 * sh["S"],
                     C_CERT * 2.0 ** -11 * cd["S_pert"], C_CERT * 2.0 ** -11 * sh["S"]])
    w("fig1-ratchet-floor.dat",
      "K meas8 meas11 Spert Sterm pred8ratchet pred8term pred11ratchet pred11term", rows)
    return rows


def fig2():
    p23 = load("pilot23_results.json")
    tr = p23["e_escape_traces"]["diabetes_s0_e5m2"]
    edge = p23["w_windows"]["s1.01"]["edge_orbit"]
    del edge
    rows = []
    for i, (ex, t) in enumerate(zip(tr["exact"], tr["tops"])):
        rows.append([i, ex, t])
    w("fig2-escape.dat", "step exact e5m2", rows)
    # the certified upper edge of each of the six steps: e_escape_traces[..]["u"]
    rows = [[l + 1, e] for l, e in enumerate(tr["u"])]
    w("fig2-edge.dat", "step edge", rows)
    rows = []
    for s in ("s1.0", "s1.01", "s1.02", "s1.035", "s1.05"):
        d = p23["w_windows"][s]
        rows.append([float(s[1:]), max(d["delta_p4"], 0.0), d["delta_p5"], d["delta_p8"]])
    w("fig2-delta.dat", "safety delta4 delta5 delta8", rows)
    return rows


def fig3():
    p21 = load("pilot21_results.json")
    ks = p21["D"]["ksweep"]
    fam = {"e5m2": "E5M2", "e4m3": "E4M3", "bf16": "bf16"}
    pts = []
    for short in fam:
        rows = [[ks[f"{short}@K{K}"]["bits"], ks[f"{short}@K{K}"]["err_med"]] for K in range(2, 7)]
        rows.sort()
        w(f"fig3-{short}.dat", "bits err", rows)
        pts += [(b, e) for b, e in rows]
    rows = []
    for k, v in p21["D"]["ladder"].items():
        body = k.split("^")[0]
        m = v["m"]
        rows.append([v["bits"], v["err_med"], body, 6 - m, m])
        pts.append((v["bits"], v["err_med"]))
    rows.sort()
    w("fig3-ladder.dat", "bits err body six_m m", rows)
    # the measured frontier: ascending bits, keep a point only if it beats every cheaper one
    fr, best = [], None
    for b, e in sorted(pts):
        if best is None or e < best * (1 - 1e-12):
            fr.append([b, e])
            best = e
    w("fig3-frontier.dat", "bits err", fr)
    return rows


def main():
    os.makedirs(OUT, exist_ok=True)
    fig1()
    fig2()
    fig3()
    print("\nwrote", OUT)


if __name__ == "__main__":
    main()
