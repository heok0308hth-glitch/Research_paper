#!/usr/bin/env python3
r"""
Build the single self-contained TeX file of the paper.

The draft is maintained as main.tex plus sections/*.tex, figures/*.tex and
figures/data/*.dat, and references.bib.  For review and for the record a single
file is wanted that compiles anywhere with nothing beside it.  This script writes
that file:

  * every figures/data/*.dat is carried as a filecontents* block, so the figures
    write their own coordinates on the first pass (TeX needs a second pass, which
    tectonic and latexmk do themselves);
  * references.bib is carried the same way;
  * \input{sections/...} and \input{figures/...} are replaced by the file bodies,
    each behind a "% --- BEGIN <path> ---" marker so the two forms stay diffable;
  * \bibliography{references} is left in place, reading the block above it.

Usage:  python3 make_standalone.py [output.tex]
Default output: ../../../downloads/iclr-2028-paper-final.tex
The script is deterministic: the same sources give a byte-identical file.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SECT = os.path.join(HERE, "sections")
FIG = os.path.join(HERE, "figures")
DATA = os.path.join(FIG, "data")
DEFAULT_OUT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "downloads",
                                            "iclr-2028-paper-final.tex"))
if not os.path.isdir(os.path.dirname(DEFAULT_OUT)):
    # packaged layout (reproduce/paper/): write beside the sources instead
    DEFAULT_OUT = os.path.join(HERE, "iclr-2028-paper-final.tex")

HEADER = """% ---------------------------------------------------------------------------
% Draft. The camera-ready must use the official ICLR 2028 style file
% (iclr2028_conference.sty); this file uses a neutral article layout so the
% text, tables and numbers can be reviewed before the style is applied.
%
% This file is generated by paper/make_standalone.py from main.tex, sections/,
% figures/ and references.bib.  Edit those; do not edit this copy.
% It is self-contained: it writes its own figure coordinates and bibliography.
% ---------------------------------------------------------------------------
"""


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def filecontents(path, body):
    rel = os.path.relpath(path, HERE)
    if not body.endswith("\n"):
        body += "\n"
    return ("\\begin{filecontents*}[overwrite]{%s}\n%s\\end{filecontents*}\n"
            % (rel, body))


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    parts = [HEADER]

    for f in sorted(os.listdir(DATA)):
        if f.endswith(".dat"):
            parts.append(filecontents(os.path.join(DATA, f),
                                      read(os.path.join(DATA, f))))
    parts.append(filecontents(os.path.join(HERE, "references.bib"),
                              read(os.path.join(HERE, "references.bib"))))
    parts.append("\n")

    main_tex = read(os.path.join(HERE, "main.tex"))
    # drop the leading comment block of main.tex (replaced by HEADER)
    main_tex = re.sub(r"\A(?:%[^\n]*\n)+", "", main_tex)

    def inline(m):
        target = m.group(1).strip()
        path = os.path.join(HERE, target + ".tex")
        return ("%% --- BEGIN %s.tex ---\n%s\n%% --- END %s.tex ---"
                % (target, read(path).rstrip("\n"), target))

    body = re.sub(r"\\input\{([^}]+)\}", inline, main_tex)
    # the sections themselves \input the figures, so inline a second pass
    body = re.sub(r"\\input\{([^}]+)\}", inline, body)
    if "\\input{" in body:
        sys.exit("an \\input survived the inlining: " +
                 ", ".join(re.findall(r"\\input\{([^}]+)\}", body)))
    text = "".join(parts) + body
    if not text.endswith("\n"):
        text += "\n"
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {out_path} ({len(text)} bytes, "
          f"{text.count(chr(10))} lines)")
    for marker in sorted(set(re.findall(r"% --- BEGIN ([^\n]+) ---", text))):
        print("  inlined", marker)


if __name__ == "__main__":
    main()
